// ===== Active Language State =====
let currentLang = localStorage.getItem('mn_lang') || 'en';

function t(key) {
  return (I18N[currentLang] && I18N[currentLang][key]) || I18N.en[key] || key;
}

function setLang(l) {
  if (!LANGUAGES[l]) l = 'en';
  currentLang = l;
  localStorage.setItem('mn_lang', l);
  applyTranslations();
  // Only show toast if toast function exists
  if (typeof toast === 'function') {
    toast(LANGUAGES[l].name + ' ✓', 'success', LANGUAGES[l].flag);
  }
}

function applyTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const k = el.getAttribute('data-i18n');
    if (k) el.textContent = t(k);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    el.placeholder = t(el.getAttribute('data-i18n-placeholder'));
  });
  const sel = document.getElementById('langSelect');
  if (sel) sel.value = currentLang;
  if (typeof renderCurrentScreen === 'function') renderCurrentScreen();
}
